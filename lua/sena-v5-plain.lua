local orderedKeys = {}
for en in pairs(Translations) do
    table.insert(orderedKeys, en)
end
table.sort(orderedKeys, function(a, b) return #a > #b end)

local function escapePattern(s)
    return (s:gsub("[%^%$%(%)%%%.%[%]%*%+%-%?]", "%%%1"))
end

local cache = {}
local function translateText(text)
    if not text or type(text) ~= "string" or text == "" then return text end
    local hit = cache[text]
    if hit ~= nil then return hit end

    if Translations[text] then
        cache[text] = Translations[text]
        return Translations[text]
    end

    for _, en in ipairs(orderedKeys) do
        if text:find(en, 1, true) then
            local replaced = text:gsub(escapePattern(en), function() return Translations[en] end)
            cache[text] = replaced
            return replaced
        end
    end

    cache[text] = text
    return text
end

local TEXT_CLASSES = { TextLabel = true, TextButton = true, TextBox = true }

local function isTextObject(obj)
    for class in pairs(TEXT_CLASSES) do
        local ok, res = pcall(function() return obj:IsA(class) end)
        if ok and res then return true end
    end
    return false
end

local function getRoots()
    local roots = {}
    pcall(function() table.insert(roots, game:GetService("CoreGui")) end)
    pcall(function() table.insert(roots, game:GetService("Players").LocalPlayer.PlayerGui) end)
    return roots
end

local function scanOnce(budget)
    local spent = 0
    for _, root in ipairs(getRoots()) do
        local ok, list = pcall(function() return root:GetDescendants() end)
        if ok and list then
            for _, gui in ipairs(list) do
                if isTextObject(gui) then
                    local ok2, text = pcall(function() return gui.Text end)
                    if ok2 and type(text) == "string" and text ~= "" then
                        local want = translateText(text)
                        if want ~= text then
                            pcall(function() gui.Text = want end)
                        end
                        spent = spent + 1
                        if spent >= budget then return spent end
                    end
                end
            end
        end
    end
    return spent
end

local function scanAll()
    local spent = 1
    while spent > 0 do
        spent = scanOnce(80)
        if spent >= 80 then task.wait(0.05) end
    end
end

-- 劫持 Instance 元表（关键：不是 game 的元表）
local function tryHook()
    local sample = Instance.new("TextLabel")
    local mt = getrawmetatable(sample)
    if type(mt) ~= "table" then
        pcall(function() sample:Destroy() end)
        return false
    end

    local oldNewIndex = mt.__newindex
    setreadonly(mt, false)
    mt.__newindex = newcclosure(function(t, k, v)
        if k == "Text" and type(v) == "string" then
            local ok, res = pcall(translateText, v)
            if ok and res ~= v then v = res end
        end
        if oldNewIndex then
            return oldNewIndex(t, k, v)
        end
        -- 极少数执行器没有原生 __newindex，改写失败就交给扫描兜底
    end)
    setreadonly(mt, true)

    local probeKey = orderedKeys[1]
    local got
    pcall(function()
        sample.Text = probeKey
        got = sample.Text
    end)
    pcall(function() sample:Destroy() end)

    local works = (probeKey == nil) or (got ~= probeKey)
    if not works then
        pcall(function()
            setreadonly(mt, false)
            mt.__newindex = oldNewIndex
            setreadonly(mt, true)
        end)
    end
    return works
end

