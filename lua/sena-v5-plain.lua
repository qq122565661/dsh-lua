local function engine()
    task.wait(0.5)

    local hooked = false
    local okHook = pcall(function() hooked = tryHook() end)
    if not okHook then hooked = false end
    if not hooked then
        warn("Instance 元表劫持无效，已切换为定时扫描")
    end

    pcall(scanAll)

    while true do
        pcall(scanAll)
        task.wait(1.5)
    end
end

